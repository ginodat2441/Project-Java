      (SELECT MIN(h.CREATED_AT) FROM BILL_HISTORY h
        WHERE h.BILL_ID = b.ID AND h.NEW_STATUS = 3),
      b.UPDATED_AT)
    WHERE b.STATUS IN (3,5) AND b.COMPLETED_AT IS NULL~';
END;
