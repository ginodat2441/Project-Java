-- Bring existing tables forward before creating indexes and constraints that use new columns.
DECLARE
  n NUMBER;
  invalid_rows NUMBER;
  product_rows NUMBER;
  has_physical_quantity NUMBER;
  has_balance_check NUMBER;
  v008_applied NUMBER;
  needs_v008 NUMBER := 0;
  next_number NUMBER;

  PROCEDURE add_column(t VARCHAR2, c VARCHAR2, definition VARCHAR2) IS
    column_count NUMBER;
  BEGIN
    SELECT COUNT(*) INTO column_count
      FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = t AND COLUMN_NAME = c;
    IF column_count = 0 THEN
      EXECUTE IMMEDIATE 'ALTER TABLE "' || t || '" ADD ("' || c || '" ' || definition || ')';
    END IF;
  END;

  -- Preserve the pre-V008 data only when a legacy stock conversion is required.
  PROCEDURE snapshot(t VARCHAR2, b VARCHAR2) IS
    table_count NUMBER;
  BEGIN
    SELECT COUNT(*) INTO table_count
      FROM USER_TABLES
     WHERE TABLE_NAME = b;
    IF table_count = 0 THEN
      EXECUTE IMMEDIATE 'CREATE TABLE "' || b || '" AS SELECT * FROM "' || t || '"';
    END IF;
  END;
BEGIN
  SELECT COUNT(*) INTO has_physical_quantity
    FROM USER_TAB_COLUMNS
   WHERE TABLE_NAME = 'PRODUCT_DETAIL' AND COLUMN_NAME = 'PHYSICAL_QUANTITY';
  SELECT COUNT(*) INTO has_balance_check
    FROM USER_CONSTRAINTS
   WHERE TABLE_NAME = 'PRODUCT_DETAIL' AND CONSTRAINT_NAME = 'CK_PD_BALANCE_V8';
  SELECT COUNT(*) INTO v008_applied
    FROM SHOP_MIGRATION
   WHERE VERSION = 'V008';
  SELECT COUNT(*) INTO product_rows FROM PRODUCT_DETAIL;

  IF v008_applied > 0 AND has_physical_quantity = 0 AND product_rows > 0 THEN
    RAISE_APPLICATION_ERROR(-20074, 'V008 is recorded but PRODUCT_DETAIL.PHYSICAL_QUANTITY is missing; reconcile the schema before retrying.');
  END IF;

  IF v008_applied = 0
     AND (has_physical_quantity = 0 OR (has_balance_check = 0 AND product_rows > 0)) THEN
    needs_v008 := 1;
    snapshot('PRODUCT_DETAIL', 'SCHEMA_UPG_PD');
    snapshot('BILL', 'SCHEMA_UPG_BILL');
    snapshot('BILL_DETAIL', 'SCHEMA_UPG_BD');
    snapshot('INVENTORY_DOCUMENT', 'SCHEMA_UPG_INV_DOC');
    snapshot('INVENTORY_DOCUMENT_LINE', 'SCHEMA_UPG_INV_LINE');
    snapshot('INVENTORY_HISTORY', 'SCHEMA_UPG_INV_HISTORY');
    snapshot('PRODUCT', 'SCHEMA_UPG_PRODUCT');
    snapshot('ADMIN_AUDIT', 'SCHEMA_UPG_AUDIT');
  END IF;

  add_column('MANAGER', 'AUTH_VERSION', 'NUMBER DEFAULT 0 NOT NULL');
  add_column('USERS', 'AUTH_VERSION', 'NUMBER DEFAULT 0 NOT NULL');
  add_column('PRODUCT', 'CATEGORY_ID', 'NUMBER');
  add_column('PRODUCT', 'AVERAGE_COST', 'NUMBER(24,8)');
  add_column('BILL', 'VOUCHER_CODE', 'VARCHAR2(50)');
  add_column('BILL', 'CARRIER', 'NVARCHAR2(150)');
  add_column('BILL', 'TRACKING_CODE', 'VARCHAR2(150)');
  add_column('BILL', 'STOCK_RESERVED', 'NUMBER(1) DEFAULT 0 NOT NULL');
  add_column('BILL', 'COMPLETED_AT', 'TIMESTAMP');
  add_column('BILL', 'RETURNED_AT', 'TIMESTAMP');
  add_column('BILL', 'RETURN_STATUS', 'VARCHAR2(12) DEFAULT ''NONE'' NOT NULL');
  add_column('BILL', 'RETURN_VALUE', 'NUMBER(15,2) DEFAULT 0 NOT NULL');
  add_column('BILL', 'DISPATCHED', 'NUMBER(1) DEFAULT 0 NOT NULL');
  add_column('BILL', 'SHIPPING_SERVICE', 'VARCHAR2(100)');
  add_column('BILL', 'SHIPPING_SERVICE_NAME', 'NVARCHAR2(255)');
  add_column('BILL', 'SHIPPING_QUOTED_AT', 'TIMESTAMP');
  add_column('BILL_DETAIL', 'COST_UNIT', 'NUMBER(24,8)');
  add_column('BILL_DETAIL', 'COST_TOTAL', 'NUMBER(20,0)');
  add_column('PRODUCT_DETAIL', 'PHYSICAL_QUANTITY', 'NUMBER(10) DEFAULT 0 NOT NULL');
  add_column('PRODUCT_DETAIL', 'RESERVED_QUANTITY', 'NUMBER(10) DEFAULT 0 NOT NULL');
  add_column('PRODUCT_DETAIL', 'AVERAGE_COST', 'NUMBER(24,8)');
  add_column('PRODUCT_DETAIL', 'KNOWN_VALUE', 'NUMBER(30,8) DEFAULT 0 NOT NULL');
  add_column('PRODUCT_DETAIL', 'UNKNOWN_QUANTITY', 'NUMBER(24,8) DEFAULT 0 NOT NULL');
  add_column('PRODUCT_DETAIL', 'COST_RECONCILED_AT', 'TIMESTAMP');
  add_column('PRODUCT_DETAIL', 'STOCK_VERSION', 'NUMBER DEFAULT 0 NOT NULL');
  add_column('INVENTORY_DOCUMENT', 'REVENUE_DELTA', 'NUMBER(20,2) DEFAULT 0 NOT NULL');
  add_column('INVENTORY_DOCUMENT_LINE', 'UNIT_COST', 'NUMBER(14,2)');
  add_column('INVENTORY_DOCUMENT_LINE', 'COST_UNIT', 'NUMBER(24,8)');
  add_column('INVENTORY_DOCUMENT_LINE', 'EXPECTED_RESERVED', 'NUMBER(10)');
  add_column('INVENTORY_DOCUMENT_LINE', 'EXPECTED_VERSION', 'NUMBER');
  add_column('INVENTORY_DOCUMENT_LINE', 'PHYSICAL_BEFORE', 'NUMBER(10)');
  add_column('INVENTORY_DOCUMENT_LINE', 'PHYSICAL_AFTER', 'NUMBER(10)');
  add_column('INVENTORY_DOCUMENT_LINE', 'RESERVED_BEFORE', 'NUMBER(10)');
  add_column('INVENTORY_DOCUMENT_LINE', 'RESERVED_AFTER', 'NUMBER(10)');
  add_column('INVENTORY_DOCUMENT_LINE', 'VALUE_BEFORE', 'NUMBER(30,8)');
  add_column('INVENTORY_DOCUMENT_LINE', 'VALUE_AFTER', 'NUMBER(30,8)');
  add_column('INVENTORY_DOCUMENT_LINE', 'COGS_VALUE', 'NUMBER(20,0)');
  add_column('INVENTORY_HISTORY', 'DOCUMENT_ID', 'NUMBER');
  add_column('INVENTORY_HISTORY', 'MOVEMENT_TYPE', 'VARCHAR2(15)');
  add_column('INVENTORY_HISTORY', 'BEFORE_QUANTITY', 'NUMBER(10)');
  add_column('INVENTORY_HISTORY', 'AFTER_QUANTITY', 'NUMBER(10)');
  add_column('INVENTORY_HISTORY', 'PHYSICAL_CHANGE', 'NUMBER(10)');
  add_column('INVENTORY_HISTORY', 'RESERVED_CHANGE', 'NUMBER(10)');
  add_column('INVENTORY_HISTORY', 'PHYSICAL_BEFORE', 'NUMBER(10)');
  add_column('INVENTORY_HISTORY', 'PHYSICAL_AFTER', 'NUMBER(10)');
  add_column('INVENTORY_HISTORY', 'RESERVED_BEFORE', 'NUMBER(10)');
  add_column('INVENTORY_HISTORY', 'RESERVED_AFTER', 'NUMBER(10)');
  add_column('INVENTORY_HISTORY', 'VALUE_BEFORE', 'NUMBER(30,8)');
  add_column('INVENTORY_HISTORY', 'VALUE_AFTER', 'NUMBER(30,8)');
  add_column('INVENTORY_HISTORY', 'HISTORY_SCOPE', 'VARCHAR2(20) DEFAULT ''AVAILABLE_LEGACY'' NOT NULL');
  add_column('ADMIN_AUDIT', 'BEFORE_DATA', 'CLOB');
  add_column('ADMIN_AUDIT', 'AFTER_DATA', 'CLOB');
  add_column('ADMIN_AUDIT', 'REASON', 'NVARCHAR2(500)');
  add_column('VOUCHER', 'ENDS_AT', 'TIMESTAMP');
  add_column('VOUCHER', 'NEW_ACCOUNT_DAYS', 'NUMBER(5)');
  add_column('VOUCHER', 'NO_PREVIOUS_ORDERS', 'NUMBER(1) DEFAULT 0 NOT NULL');
  add_column('VOUCHER', 'MINIMUM_ORDERS', 'NUMBER(10)');

  IF needs_v008 = 1 THEN
    SELECT COUNT(*) INTO invalid_rows FROM PRODUCT_DETAIL WHERE QUANTITY < 0;
    IF invalid_rows > 0 THEN
      RAISE_APPLICATION_ERROR(-20070, 'Negative legacy available stock; reconcile before schema upgrade.');
    END IF;

    EXECUTE IMMEDIATE q'~SELECT COUNT(*) FROM BILL b
      WHERE b.DELETE_FLAG = 0 AND b.STATUS IN (0,1) AND b.STOCK_RESERVED = 0
        AND EXISTS (SELECT 1 FROM BILL_DETAIL d WHERE d.BILL_ID = b.ID AND d.DELETE_FLAG = 0)~'
      INTO invalid_rows;
    IF invalid_rows > 0 THEN
      RAISE_APPLICATION_ERROR(-20071, 'Open legacy orders lack documented reservations; reconcile them before schema upgrade.');
    END IF;

    EXECUTE IMMEDIATE q'~SELECT COUNT(*) FROM PRODUCT_DETAIL v
      WHERE v.QUANTITY + (
        SELECT NVL(SUM(d.QUANTITY),0)
          FROM BILL_DETAIL d JOIN BILL b ON b.ID = d.BILL_ID
         WHERE d.PRODUCT_DETAIL_ID = v.ID AND d.DELETE_FLAG = 0
           AND b.DELETE_FLAG = 0 AND b.STATUS IN (0,1) AND b.STOCK_RESERVED = 1
      ) > 2147483647~' INTO invalid_rows;
    IF invalid_rows > 0 THEN
      RAISE_APPLICATION_ERROR(-20072, 'Legacy physical stock exceeds the supported quantity; reconcile before schema upgrade.');
    END IF;

    SELECT COUNT(*) INTO invalid_rows
      FROM BILL_DETAIL d
      JOIN BILL b ON b.ID = d.BILL_ID
      JOIN PRODUCT_DETAIL v ON v.ID = d.PRODUCT_DETAIL_ID
      JOIN PRODUCT p ON p.ID = v.PRODUCT_ID
     WHERE b.DELETE_FLAG = 0 AND b.STATUS IN (0,1) AND d.DELETE_FLAG = 0
       AND (v.DELETE_FLAG = 1 OR p.DELETE_FLAG = 1);
    IF invalid_rows > 0 THEN
      RAISE_APPLICATION_ERROR(-20073, 'Open orders reference deleted stock; reconcile before schema upgrade.');
    END IF;

    EXECUTE IMMEDIATE q'~UPDATE PRODUCT_DETAIL pd
      SET RESERVED_QUANTITY = (
        SELECT NVL(SUM(d.QUANTITY),0)
          FROM BILL_DETAIL d JOIN BILL b ON b.ID = d.BILL_ID
         WHERE d.PRODUCT_DETAIL_ID = pd.ID AND d.DELETE_FLAG = 0
           AND b.DELETE_FLAG = 0 AND b.STOCK_RESERVED = 1 AND b.STATUS IN (0,1)
      )~';
    EXECUTE IMMEDIATE q'~UPDATE PRODUCT_DETAIL
      SET PHYSICAL_QUANTITY = QUANTITY + RESERVED_QUANTITY,
          AVERAGE_COST = NULL,
          KNOWN_VALUE = 0,
          UNKNOWN_QUANTITY = QUANTITY + RESERVED_QUANTITY~';
    EXECUTE IMMEDIATE q'~UPDATE BILL
      SET DISPATCHED = CASE WHEN STATUS IN (2,3,5) THEN 1 ELSE 0 END,
          STOCK_RESERVED = CASE WHEN STATUS IN (0,1) THEN STOCK_RESERVED ELSE 0 END~';
    EXECUTE IMMEDIATE 'UPDATE BILL_DETAIL SET COST_UNIT = NULL';
    INSERT INTO SHOP_MIGRATION (VERSION)
      SELECT 'V008' FROM DUAL
       WHERE NOT EXISTS (SELECT 1 FROM SHOP_MIGRATION WHERE VERSION = 'V008');
    COMMIT;
  END IF;

  FOR c IN (
    SELECT CONSTRAINT_NAME, SEARCH_CONDITION_VC
      FROM USER_CONSTRAINTS
     WHERE TABLE_NAME = 'INVENTORY_DOCUMENT'
       AND CONSTRAINT_TYPE = 'C'
       AND SEARCH_CONDITION_VC IS NOT NULL
  ) LOOP
    IF INSTR(UPPER(c.SEARCH_CONDITION_VC), 'DOC_TYPE') > 0
       AND INSTR(UPPER(c.SEARCH_CONDITION_VC), 'RECEIPT') > 0
       AND INSTR(UPPER(c.SEARCH_CONDITION_VC), 'DISPATCH') = 0 THEN
      EXECUTE IMMEDIATE 'ALTER TABLE INVENTORY_DOCUMENT DROP CONSTRAINT "' || c.CONSTRAINT_NAME || '"';
    END IF;
  END LOOP;

  SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS
   WHERE TABLE_NAME = 'BILL' AND CONSTRAINT_NAME = 'CK_BILL_STATUS';
  IF n > 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE BILL DROP CONSTRAINT CK_BILL_STATUS';
  END IF;

  SELECT COUNT(*) INTO n FROM USER_SEQUENCES
   WHERE SEQUENCE_NAME = 'SHOP_PRODUCT_CODE_SEQ';
  IF n = 0 THEN
    SELECT GREATEST(130, NVL(MAX(CASE
      WHEN REGEXP_LIKE(PRODUCT_CODE, '^SP[0-9]+$') THEN TO_NUMBER(SUBSTR(PRODUCT_CODE, 3))
    END), 0)) + 1
      INTO next_number FROM PRODUCT;
    EXECUTE IMMEDIATE 'CREATE SEQUENCE SHOP_PRODUCT_CODE_SEQ START WITH '
      || TO_CHAR(next_number, 'FM9999999999999999999999999990')
      || ' INCREMENT BY 1 NOCACHE NOCYCLE';
  END IF;

  SELECT COUNT(*) INTO n FROM USER_SEQUENCES
   WHERE SEQUENCE_NAME = 'SHOP_INVENTORY_SEQ';
  IF n = 0 THEN
    SELECT GREATEST(680, NVL(MAX(CASE
      WHEN REGEXP_LIKE(DOC_CODE, '^[A-Z]{2}[0-9]+$') THEN TO_NUMBER(SUBSTR(DOC_CODE, 3))
    END), 0)) + 1
      INTO next_number FROM INVENTORY_DOCUMENT;
    EXECUTE IMMEDIATE 'CREATE SEQUENCE SHOP_INVENTORY_SEQ START WITH '
      || TO_CHAR(next_number, 'FM9999999999999999999999999990')
      || ' INCREMENT BY 1 CACHE 20 NOCYCLE';
  END IF;
END;
