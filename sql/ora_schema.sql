DECLARE
  check_condition USER_CONSTRAINTS.SEARCH_CONDITION_VC%TYPE;
  constraint_status USER_CONSTRAINTS.STATUS%TYPE;

  PROCEDURE ensure_payment_check(t VARCHAR2, c VARCHAR2) IS
    existing_count NUMBER;
  BEGIN
    SELECT COUNT(*) INTO existing_count
      FROM USER_CONSTRAINTS
     WHERE TABLE_NAME = t AND CONSTRAINT_NAME = c AND CONSTRAINT_TYPE = 'C';
    IF existing_count > 0 THEN
      SELECT SEARCH_CONDITION_VC, STATUS INTO check_condition, constraint_status
        FROM USER_CONSTRAINTS
       WHERE TABLE_NAME = t AND CONSTRAINT_NAME = c AND CONSTRAINT_TYPE = 'C';
      IF INSTR(UPPER(check_condition), '''COD''') = 0
         OR INSTR(UPPER(check_condition), '''BANK''') = 0
         OR INSTR(UPPER(check_condition), '''SEPAY''') = 0
         OR INSTR(UPPER(check_condition), '''MOMO''') = 0
         OR INSTR(UPPER(check_condition), '''VNPAY''') = 0
         OR INSTR(UPPER(check_condition), 'ZALOPAY') > 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE "' || t || '" DROP CONSTRAINT "' || c || '"';
        existing_count := 0;
      ELSIF constraint_status <> 'ENABLED' THEN
        EXECUTE IMMEDIATE 'ALTER TABLE "' || t || '" ENABLE NOVALIDATE CONSTRAINT "' || c || '"';
      END IF;
    END IF;

    IF existing_count = 0 THEN
      EXECUTE IMMEDIATE 'ALTER TABLE "' || t || '" ADD CONSTRAINT "' || c
        || '" CHECK (PAYMENT_METHOD IN (''COD'',''BANK'',''SEPAY'',''MOMO'',''VNPAY'')) ENABLE NOVALIDATE';
    END IF;
  END;
BEGIN
  ensure_payment_check('BILL', 'CK_BILL_PAY_METHOD');
  ensure_payment_check('PAYMENT_HISTORY', 'CK_PH_METHOD');

