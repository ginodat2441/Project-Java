-- =====================================================================
-- 19. TRIGGER tự động cập nhật UPDATED_AT khi UPDATE
--     Tạo hàng loạt cho tất cả các bảng bằng một khối PL/SQL.
-- =====================================================================
BEGIN
  FOR t IN (SELECT column_value AS name FROM TABLE(sys.odcivarchar2list(
      'ROLES','USERS','CUSTOMER','ADDRESS','MANAGER_ROLE','MANAGER',
      'BRAND','COLOR','MATERIAL','PRODUCT','PRODUCT_DETAIL',
      'CART','CART_DETAIL','BILL','BILL_DETAIL','BILL_HISTORY','PAYMENT_HISTORY')))
  LOOP
    EXECUTE IMMEDIATE
      'CREATE OR REPLACE TRIGGER TRG_' || t.name || '_UPD ' ||
      'BEFORE UPDATE ON ' || t.name || ' ' ||
      'FOR EACH ROW ' ||
      'BEGIN ' ||
      '  :NEW.UPDATED_AT := SYSTIMESTAMP; ' ||
      'END;';
  END LOOP;
END;
