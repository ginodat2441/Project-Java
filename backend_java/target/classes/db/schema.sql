-- =====================================================================
-- 1. ROLES - Vai trò của người dùng (khách hàng)
-- =====================================================================
CREATE TABLE ROLES (
    ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ROLE_CODE    VARCHAR2(50)    NOT NULL,
    ROLE_NAME    NVARCHAR2(100)  NOT NULL,
    DESCRIPTION  NVARCHAR2(500),
    DELETE_FLAG  NUMBER(1)       DEFAULT 0 NOT NULL,
    CREATED_AT   TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT   TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_ROLES_CODE UNIQUE (ROLE_CODE),
    CONSTRAINT CK_ROLES_DEL  CHECK (DELETE_FLAG IN (0,1))
);

-- =====================================================================
-- 2. USERS - Tài khoản đăng nhập của khách hàng
-- =====================================================================
CREATE TABLE USERS (
    ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ROLE_ID        NUMBER          NOT NULL,
    USERNAME       VARCHAR2(100)   NOT NULL,
    EMAIL          VARCHAR2(255)   NOT NULL,
    PASSWORD_HASH  VARCHAR2(255)   NOT NULL,
    STATUS         NUMBER(1)       DEFAULT 1 NOT NULL,   -- 1: hoạt động, 0: bị khóa
    LAST_LOGIN_AT  TIMESTAMP,
    DELETE_FLAG    NUMBER(1)       DEFAULT 0 NOT NULL,
    CREATED_AT     TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT     TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_USERS_USERNAME UNIQUE (USERNAME),
    CONSTRAINT UQ_USERS_EMAIL    UNIQUE (EMAIL),
    CONSTRAINT FK_USERS_ROLE     FOREIGN KEY (ROLE_ID) REFERENCES ROLES(ID),
    CONSTRAINT CK_USERS_STATUS   CHECK (STATUS IN (0,1)),
    CONSTRAINT CK_USERS_DEL      CHECK (DELETE_FLAG IN (0,1))
);

-- =====================================================================
-- 3. CUSTOMER - Thông tin khách hàng (1-1 với USERS)
-- =====================================================================
