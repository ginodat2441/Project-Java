-- 1. SELECT + WHERE + ORDER BY
SELECT * FROM PRODUCT WHERE DELETE_FLAG = 0 ORDER BY CREATED_AT DESC;

-- 2. INNER JOIN nhiều bảng
SELECT p.PRODUCT_NAME, b.BRAND_NAME, m.MATERIAL_NAME
  FROM PRODUCT p JOIN BRAND b ON b.ID = p.BRAND_ID JOIN MATERIAL m ON m.ID = p.MATERIAL_ID;

-- 3. LEFT JOIN: sản phẩm chưa có biến thể nào
SELECT p.ID, p.PRODUCT_NAME
  FROM PRODUCT p LEFT JOIN PRODUCT_DETAIL pd ON pd.PRODUCT_ID = p.ID
 WHERE pd.ID IS NULL;

-- 4. GROUP BY + HAVING: thương hiệu có từ 2 sản phẩm trở lên
SELECT b.BRAND_NAME, COUNT(*) AS SO_SP
  FROM PRODUCT p JOIN BRAND b ON b.ID = p.BRAND_ID
 GROUP BY b.BRAND_NAME HAVING COUNT(*) >= 2;

-- 5. Subquery: biến thể có giá cao hơn giá trung bình
SELECT * FROM PRODUCT_DETAIL WHERE PRICE > (SELECT AVG(PRICE) FROM PRODUCT_DETAIL);

-- 6. EXISTS: khách đã từng mua hàng
SELECT c.* FROM CUSTOMER c WHERE EXISTS (SELECT 1 FROM BILL b WHERE b.CUSTOMER_ID = c.ID);

-- 7. NOT EXISTS: khách chưa mua lần nào
SELECT c.* FROM CUSTOMER c WHERE NOT EXISTS (SELECT 1 FROM BILL b WHERE b.CUSTOMER_ID = c.ID);

-- 8. Tổng chi tiêu mỗi khách
SELECT c.FULL_NAME, SUM(b.TOTAL_AMOUNT) AS TONG_CHI
  FROM CUSTOMER c JOIN BILL b ON b.CUSTOMER_ID = c.ID AND b.STATUS = 3
 GROUP BY c.FULL_NAME ORDER BY TONG_CHI DESC;

-- 9. Hàm cửa sổ: xếp hạng sản phẩm theo doanh thu
SELECT p.PRODUCT_NAME, SUM(bd.TOTAL_PRICE) AS DT,
       RANK() OVER (ORDER BY SUM(bd.TOTAL_PRICE) DESC) AS XEP_HANG
  FROM BILL_DETAIL bd JOIN PRODUCT_DETAIL pd ON pd.ID = bd.PRODUCT_DETAIL_ID
  JOIN PRODUCT p ON p.ID = pd.PRODUCT_ID
 GROUP BY p.PRODUCT_NAME;

-- 10. CASE WHEN: tên trạng thái đơn
SELECT BILL_CODE,
       CASE STATUS WHEN 0 THEN 'Chờ xác nhận' WHEN 1 THEN 'Đã xác nhận' WHEN 2 THEN 'Đang giao'
                   WHEN 3 THEN 'Hoàn thành' WHEN 4 THEN 'Đã hủy' ELSE 'Trả hàng' END AS TRANG_THAI
  FROM BILL;

-- 11. Phân trang Oracle 12c
SELECT * FROM PRODUCT ORDER BY ID OFFSET 0 ROWS FETCH NEXT 10 ROWS ONLY;

-- 12. Lịch sử đổi trạng thái của một đơn
SELECT bh.CREATED_AT, bh.OLD_STATUS, bh.NEW_STATUS, m.FULL_NAME AS NGUOI_XU_LY
  FROM BILL_HISTORY bh LEFT JOIN MANAGER m ON m.ID = bh.MANAGER_ID
 WHERE bh.BILL_ID = 1 ORDER BY bh.CREATED_AT;
