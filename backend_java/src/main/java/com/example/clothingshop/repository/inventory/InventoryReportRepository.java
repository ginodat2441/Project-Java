package com.example.clothingshop.repository.inventory;

import com.example.clothingshop.repository.admin.AdminRepository;
import java.time.*;
import java.util.*;
import org.springframework.stereotype.Repository;

@Repository
public class InventoryReportRepository {
  private final AdminRepository db;

  public InventoryReportRepository(AdminRepository db) {
    this.db = db;
  }

  public Map<String, Object> report(LocalDate from, LocalDate to, String q, int page) {
    LocalDate start = from == null ? LocalDate.now().withDayOfMonth(1) : from,
        end = to == null ? LocalDate.now() : to;
    if (end.isBefore(start)) throw new IllegalArgumentException("Ngày kết thúc trước ngày bắt đầu");
    String sql =
        """
SELECT v.ID,v.SKU,p.PRODUCT_CODE,p.PRODUCT_NAME,c.COLOR_NAME,v.SIZE_NAME,
v.QUANTITY-NVL(h.A_START,0) OPENING,v.QUANTITY-NVL(h.A_END,0) CLOSING,
CASE WHEN NVL(h.LEGACY_START,0)=0 THEN v.PHYSICAL_QUANTITY-NVL(h.P_START,0) END PHYSICAL_OPENING,
CASE WHEN NVL(h.LEGACY_END,0)=0 THEN v.PHYSICAL_QUANTITY-NVL(h.P_END,0) END PHYSICAL_CLOSING,
CASE WHEN NVL(h.LEGACY_START,0)=0 THEN v.RESERVED_QUANTITY-NVL(h.R_START,0) END RESERVED_OPENING,
CASE WHEN NVL(h.LEGACY_END,0)=0 THEN v.RESERVED_QUANTITY-NVL(h.R_END,0) END RESERVED_CLOSING,
NVL(h.RECEIPT,0) RECEIPT,NVL(h.ISSUE,0) ISSUE,NVL(h.DISPATCH,0) DISPATCH,
NVL(h.RESERVE,0) RESERVED,NVL(h.RELEASED,0) RELEASED,NVL(h.RETURNED,0) RETURNED,
NVL(h.ADJUSTMENT,0) ADJUSTMENT,NVL(h.SALE,0) SALE,NVL(h.CANCELLED,0) CANCELLED,
NVL(h.LEGACY_START,0) LEGACY_ROWS
FROM PRODUCT_DETAIL v JOIN PRODUCT p ON p.ID=v.PRODUCT_ID JOIN COLOR c ON c.ID=v.COLOR_ID
LEFT JOIN (SELECT PRODUCT_DETAIL_ID,
 SUM(CASE WHEN CREATED_AT>=:f THEN QUANTITY_CHANGE ELSE 0 END) A_START,
 SUM(CASE WHEN CREATED_AT>=:e THEN QUANTITY_CHANGE ELSE 0 END) A_END,
 SUM(CASE WHEN CREATED_AT>=:f THEN PHYSICAL_CHANGE ELSE 0 END) P_START,
 SUM(CASE WHEN CREATED_AT>=:e THEN PHYSICAL_CHANGE ELSE 0 END) P_END,
 SUM(CASE WHEN CREATED_AT>=:f THEN RESERVED_CHANGE ELSE 0 END) R_START,
 SUM(CASE WHEN CREATED_AT>=:e THEN RESERVED_CHANGE ELSE 0 END) R_END,
 SUM(CASE WHEN CREATED_AT>=:f AND HISTORY_SCOPE<>'PHYSICAL_V8' THEN 1 ELSE 0 END) LEGACY_START,
 SUM(CASE WHEN CREATED_AT>=:e AND HISTORY_SCOPE<>'PHYSICAL_V8' THEN 1 ELSE 0 END) LEGACY_END,
 SUM(CASE WHEN CREATED_AT>=:f AND CREATED_AT<:e AND MOVEMENT_TYPE='RECEIPT' THEN QUANTITY_CHANGE ELSE 0 END) RECEIPT,
 SUM(CASE WHEN CREATED_AT>=:f AND CREATED_AT<:e AND MOVEMENT_TYPE='ISSUE' THEN -QUANTITY_CHANGE ELSE 0 END) ISSUE,
 SUM(CASE WHEN CREATED_AT>=:f AND CREATED_AT<:e AND MOVEMENT_TYPE='DISPATCH' THEN -PHYSICAL_CHANGE ELSE 0 END) DISPATCH,
 SUM(CASE WHEN CREATED_AT>=:f AND CREATED_AT<:e AND MOVEMENT_TYPE='RESERVE' THEN RESERVED_CHANGE ELSE 0 END) RESERVE,
 SUM(CASE WHEN CREATED_AT>=:f AND CREATED_AT<:e AND MOVEMENT_TYPE='RELEASE' THEN -RESERVED_CHANGE ELSE 0 END) RELEASED,
 SUM(CASE WHEN CREATED_AT>=:f AND CREATED_AT<:e AND MOVEMENT_TYPE='RETURN' THEN QUANTITY_CHANGE ELSE 0 END) RETURNED,
 SUM(CASE WHEN CREATED_AT>=:f AND CREATED_AT<:e AND MOVEMENT_TYPE='SALE' THEN -QUANTITY_CHANGE ELSE 0 END) SALE,
 SUM(CASE WHEN CREATED_AT>=:f AND CREATED_AT<:e AND MOVEMENT_TYPE='CANCEL' THEN QUANTITY_CHANGE ELSE 0 END) CANCELLED,
 SUM(CASE WHEN CREATED_AT>=:f AND CREATED_AT<:e AND (MOVEMENT_TYPE IN ('COUNT','REVERSAL') OR MOVEMENT_TYPE IS NULL) THEN QUANTITY_CHANGE ELSE 0 END) ADJUSTMENT
 FROM INVENTORY_HISTORY GROUP BY PRODUCT_DETAIL_ID) h ON h.PRODUCT_DETAIL_ID=v.ID
WHERE v.DELETE_FLAG=0 AND p.DELETE_FLAG=0 AND (LOWER(v.SKU) LIKE :q OR LOWER(p.PRODUCT_NAME) LIKE :q OR LOWER(p.PRODUCT_CODE) LIKE :q)
""";
    Object[] args = {
      "f",
      java.sql.Date.valueOf(start),
      "e",
      java.sql.Date.valueOf(end.plusDays(1)),
      "q",
      "%" + q.toLowerCase(Locale.ROOT) + "%"
    };
    var result =
        new LinkedHashMap<String, Object>(db.page(sql + " ORDER BY ID DESC", page, 30, args));
    result.put(
        "totals",
        db.one(
            "SELECT SUM(OPENING) OPENING,SUM(CLOSING) CLOSING,SUM(RECEIPT) RECEIPT,SUM(DISPATCH)"
                + " DISPATCH,SUM(RESERVED) RESERVED,SUM(RELEASED) RELEASED,SUM(RETURNED)"
                + " RETURNED,SUM(ISSUE) ISSUE,SUM(ADJUSTMENT) ADJUSTMENT,SUM(LEGACY_ROWS)"
                + " LEGACY_ROWS FROM ("
                + sql
                + ")",
            args));
    return result;
  }
}
