package com.example.clothingshop.admin;

/** Allocate discounts and shipping in whole VND; the last line takes the remainder. */
final class SaleAccounting {
 private SaleAccounting(){}
 static final String ALL_LINES="""
  SELECT b.ID BILL_ID,d.ID LINE_ID,d.PRODUCT_DETAIL_ID,d.QUANTITY,d.TOTAL_PRICE,d.COST_UNIT,d.COST_TOTAL,
   b.COMPLETED_AT,b.SHIPPING_FEE,b.SUB_TOTAL,
   CASE WHEN d.ID=MAX(d.ID) OVER(PARTITION BY b.ID)
    THEN b.DISCOUNT_AMOUNT-SUM(CASE WHEN b.SUB_TOTAL>0 THEN ROUND(d.TOTAL_PRICE*b.DISCOUNT_AMOUNT/b.SUB_TOTAL,0) ELSE 0 END) OVER(PARTITION BY b.ID)
     +CASE WHEN b.SUB_TOTAL>0 THEN ROUND(d.TOTAL_PRICE*b.DISCOUNT_AMOUNT/b.SUB_TOTAL,0) ELSE 0 END
    ELSE CASE WHEN b.SUB_TOTAL>0 THEN ROUND(d.TOTAL_PRICE*b.DISCOUNT_AMOUNT/b.SUB_TOTAL,0) ELSE 0 END END ALLOCATED_DISCOUNT,
   CASE WHEN d.ID=MAX(d.ID) OVER(PARTITION BY b.ID)
    THEN b.SHIPPING_FEE-SUM(CASE WHEN b.SUB_TOTAL>0 THEN ROUND(d.TOTAL_PRICE*b.SHIPPING_FEE/b.SUB_TOTAL,0) ELSE 0 END) OVER(PARTITION BY b.ID)
     +CASE WHEN b.SUB_TOTAL>0 THEN ROUND(d.TOTAL_PRICE*b.SHIPPING_FEE/b.SUB_TOTAL,0) ELSE 0 END
    ELSE CASE WHEN b.SUB_TOTAL>0 THEN ROUND(d.TOTAL_PRICE*b.SHIPPING_FEE/b.SUB_TOTAL,0) ELSE 0 END END ALLOCATED_SHIPPING
  FROM BILL b JOIN BILL_DETAIL d ON d.BILL_ID=b.ID
  WHERE b.DELETE_FLAG=0 AND d.DELETE_FLAG=0
  """;
 static final String LINES=ALL_LINES+" AND b.STATUS IN (3,5) AND b.COMPLETED_AT IS NOT NULL";
}
