CREATE SEQUENCE SHOP_INVENTORY_SEQ START WITH 1 INCREMENT BY 1 NOCYCLE;
CREATE TABLE INVENTORY_DOCUMENT (
 ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 DOC_CODE VARCHAR2(50) NOT NULL UNIQUE,
 DOC_TYPE VARCHAR2(15) NOT NULL CHECK(DOC_TYPE IN ('RECEIPT','ISSUE','COUNT','RETURN','REVERSAL','SALE','CANCEL')),
 STATUS VARCHAR2(12) DEFAULT 'DRAFT' NOT NULL CHECK(STATUS IN ('DRAFT','POSTED','CANCELLED')),
 REASON NVARCHAR2(500) NOT NULL,
 BILL_ID NUMBER REFERENCES BILL(ID), SOURCE_ID NUMBER REFERENCES INVENTORY_DOCUMENT(ID),
 CREATED_BY NUMBER REFERENCES MANAGER(ID), APPROVED_BY NUMBER REFERENCES MANAGER(ID),
 CANCELLED_BY NUMBER REFERENCES MANAGER(ID), CANCEL_REASON NVARCHAR2(500),
 CREATED_AT TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL, POSTED_AT TIMESTAMP, CANCELLED_AT TIMESTAMP
);
CREATE UNIQUE INDEX UQ_INVENTORY_SALE ON INVENTORY_DOCUMENT(CASE WHEN DOC_TYPE='SALE' THEN BILL_ID END);
CREATE UNIQUE INDEX UQ_INVENTORY_CANCEL ON INVENTORY_DOCUMENT(CASE WHEN DOC_TYPE='CANCEL' THEN BILL_ID END);
CREATE UNIQUE INDEX UQ_INVENTORY_REVERSAL ON INVENTORY_DOCUMENT(CASE WHEN DOC_TYPE='REVERSAL' AND STATUS<>'CANCELLED' THEN SOURCE_ID END);
CREATE TABLE INVENTORY_DOCUMENT_LINE (
 ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 DOCUMENT_ID NUMBER NOT NULL REFERENCES INVENTORY_DOCUMENT(ID),
 PRODUCT_DETAIL_ID NUMBER NOT NULL REFERENCES PRODUCT_DETAIL(ID),
 QUANTITY NUMBER(10) NOT NULL CHECK(QUANTITY>=0),
 EXPECTED_QUANTITY NUMBER(10), BEFORE_QUANTITY NUMBER(10), AFTER_QUANTITY NUMBER(10), STOCK_DELTA NUMBER(10),
 RESTOCK NUMBER(1) DEFAULT 1 NOT NULL CHECK(RESTOCK IN (0,1)), CONDITION_NOTE NVARCHAR2(500),
 RETURN_VALUE NUMBER(15,2) DEFAULT 0 NOT NULL,
 CONSTRAINT UQ_INVENTORY_DOC_LINE UNIQUE(DOCUMENT_ID,PRODUCT_DETAIL_ID)
);
ALTER TABLE INVENTORY_HISTORY ADD (
 DOCUMENT_ID NUMBER REFERENCES INVENTORY_DOCUMENT(ID), MOVEMENT_TYPE VARCHAR2(15),
 BEFORE_QUANTITY NUMBER(10), AFTER_QUANTITY NUMBER(10)
);
ALTER TABLE BILL ADD (
 COMPLETED_AT TIMESTAMP, RETURNED_AT TIMESTAMP,
 RETURN_STATUS VARCHAR2(12) DEFAULT 'NONE' NOT NULL CHECK(RETURN_STATUS IN ('NONE','REQUESTED','PARTIAL','FULL')),
 RETURN_VALUE NUMBER(15,2) DEFAULT 0 NOT NULL CHECK(RETURN_VALUE>=0)
);
-- Best available historical completion timestamp; no historical sales/returns invented.
UPDATE BILL b SET COMPLETED_AT=COALESCE(
 (SELECT MIN(h.CREATED_AT) FROM BILL_HISTORY h WHERE h.BILL_ID=b.ID AND h.NEW_STATUS=3),b.UPDATED_AT)
 WHERE b.STATUS IN (3,5);
CREATE INDEX IDX_INV_DOC_BILL ON INVENTORY_DOCUMENT(BILL_ID,DOC_TYPE,STATUS);
CREATE INDEX IDX_INV_HISTORY_DATE ON INVENTORY_HISTORY(CREATED_AT,PRODUCT_DETAIL_ID);
CREATE INDEX IDX_BILL_COMPLETED ON BILL(COMPLETED_AT);
CREATE TABLE MANAGER_PASSWORD_RESET (
 ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 MANAGER_ID NUMBER NOT NULL REFERENCES MANAGER(ID), TOKEN_HASH VARCHAR2(64) NOT NULL UNIQUE,
 AUTH_VERSION NUMBER NOT NULL, CREATED_AT TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
 EXPIRES_AT TIMESTAMP NOT NULL, USED_AT TIMESTAMP
);
