-- Only safe while writers remain stopped and no post-upgrade transactions exist.
-- Restore the pre-upgrade application artifact after this script.
DECLARE n NUMBER; sets VARCHAR2(32000);
 PROCEDURE restore(t VARCHAR2,b VARCHAR2) IS BEGIN
  sets:='';
  FOR c IN (SELECT COLUMN_NAME FROM USER_TAB_COLUMNS WHERE TABLE_NAME=b AND COLUMN_NAME<>'ID' ORDER BY COLUMN_ID) LOOP
   IF sets IS NOT NULL THEN sets:=sets||','; END IF;
   sets:=sets||'t.'||c.COLUMN_NAME||'=b.'||c.COLUMN_NAME;
  END LOOP;
  EXECUTE IMMEDIATE 'MERGE INTO '||t||' t USING '||b||' b ON(t.ID=b.ID) WHEN MATCHED THEN UPDATE SET '||sets;
 END;
BEGIN
 SELECT COUNT(*) INTO n FROM INVENTORY_HISTORY WHERE HISTORY_SCOPE='PHYSICAL_V8';
 IF n>0 THEN RAISE_APPLICATION_ERROR(-20080,'Post-upgrade writes exist: use a reviewed full database recovery, not this rollback'); END IF;
 SELECT COUNT(*) INTO n FROM ADMIN_AUDIT a WHERE NOT EXISTS(SELECT 1 FROM V008_BACKUP_AUDIT b WHERE b.ID=a.ID);
 IF n>0 THEN RAISE_APPLICATION_ERROR(-20081,'Post-upgrade audited changes exist; full recovery must be reviewed'); END IF;
 SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME='CK_PD_BALANCE_V8';
 IF n>0 THEN EXECUTE IMMEDIATE 'ALTER TABLE PRODUCT_DETAIL DROP CONSTRAINT CK_PD_BALANCE_V8'; END IF;
 restore('PRODUCT_DETAIL','V008_BACKUP_PD');restore('BILL','V008_BACKUP_BILL');restore('BILL_DETAIL','V008_BACKUP_BD');
 restore('INVENTORY_DOCUMENT','V008_BACKUP_DOC');restore('INVENTORY_DOCUMENT_LINE','V008_BACKUP_LINE');restore('INVENTORY_HISTORY','V008_BACKUP_HISTORY');restore('PRODUCT','V008_BACKUP_PRODUCT');
 DELETE FROM SHOP_MIGRATION WHERE VERSION IN ('V008','V008_COST','V008_COST_ROUND');COMMIT;
END;
/
