WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
CREATE TABLE SHOP_MIGRATION (VERSION VARCHAR2(30) PRIMARY KEY, APPLIED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL);
CREATE TABLE CATEGORY (
 ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 CATEGORY_NAME NVARCHAR2(150) NOT NULL, PARENT_ID NUMBER REFERENCES CATEGORY(ID),
 STATUS NUMBER(1) DEFAULT 1 NOT NULL CHECK (STATUS IN (0,1)),
 CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
ALTER TABLE PRODUCT ADD CATEGORY_ID NUMBER REFERENCES CATEGORY(ID);
-- Preflight: abort rather than deleting or rewriting duplicate legacy variants.
ALTER TABLE PRODUCT_DETAIL ADD CONSTRAINT UQ_PD_COLOR_SIZE UNIQUE (PRODUCT_ID,COLOR_ID,SIZE_NAME);
CREATE TABLE PRODUCT_IMAGE (
 ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 PRODUCT_ID NUMBER NOT NULL REFERENCES PRODUCT(ID), COLOR_ID NUMBER REFERENCES COLOR(ID),
 IMAGE_URL VARCHAR2(500) NOT NULL, SORT_ORDER NUMBER DEFAULT 0 NOT NULL,
 IS_COVER NUMBER(1) DEFAULT 0 NOT NULL CHECK (IS_COVER IN (0,1))
);
INSERT INTO PRODUCT_IMAGE(PRODUCT_ID,IMAGE_URL,IS_COVER)
 SELECT ID,THUMBNAIL_URL,1 FROM PRODUCT WHERE THUMBNAIL_URL IS NOT NULL;
CREATE TABLE VOUCHER (
 ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, CODE VARCHAR2(50) NOT NULL UNIQUE,
 DISCOUNT_TYPE VARCHAR2(10) NOT NULL CHECK(DISCOUNT_TYPE IN ('PERCENT','FIXED')),
 DISCOUNT_VALUE NUMBER(15,2) NOT NULL CHECK(DISCOUNT_VALUE>0),
 MIN_ORDER NUMBER(15,2) DEFAULT 0 NOT NULL CHECK(MIN_ORDER>=0),
 MAX_DISCOUNT NUMBER(15,2) NOT NULL CHECK(MAX_DISCOUNT>=0),
 STARTS_AT TIMESTAMP NOT NULL, ENDS_AT TIMESTAMP NOT NULL,
 USAGE_LIMIT NUMBER NOT NULL CHECK(USAGE_LIMIT>=0), USED_COUNT NUMBER DEFAULT 0 NOT NULL,
 STATUS NUMBER(1) DEFAULT 1 NOT NULL CHECK(STATUS IN (0,1)),
 CHECK(ENDS_AT>STARTS_AT), CHECK(USED_COUNT>=0 AND USED_COUNT<=USAGE_LIMIT),
 CHECK(DISCOUNT_TYPE<>'PERCENT' OR DISCOUNT_VALUE<=100)
);
ALTER TABLE BILL ADD (VOUCHER_CODE VARCHAR2(50), CARRIER NVARCHAR2(150), TRACKING_CODE VARCHAR2(150),
 STOCK_RESERVED NUMBER(1) DEFAULT 0 NOT NULL CHECK(STOCK_RESERVED IN (0,1)));
-- Existing bills are left unreserved: migration must never invent stock movements.
CREATE TABLE INVENTORY_HISTORY (
 ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
