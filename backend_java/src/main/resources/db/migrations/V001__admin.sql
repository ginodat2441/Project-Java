 QUANTITY_CHANGE NUMBER NOT NULL, REASON NVARCHAR2(500) NOT NULL,
 MANAGER_ID NUMBER REFERENCES MANAGER(ID), BILL_ID NUMBER REFERENCES BILL(ID),
 CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE ADMIN_AUDIT (
 ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 MANAGER_ID NUMBER REFERENCES MANAGER(ID), ACTION VARCHAR2(80) NOT NULL,
 OBJECT_TYPE VARCHAR2(50) NOT NULL, OBJECT_ID NUMBER,
 CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
