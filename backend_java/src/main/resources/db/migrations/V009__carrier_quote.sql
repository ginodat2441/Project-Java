DECLARE n NUMBER;
 PROCEDURE addcol(c VARCHAR2,t VARCHAR2) IS BEGIN
  SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME='BILL' AND COLUMN_NAME=c;
  IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE BILL ADD ('||c||' '||t||')'; END IF;
 END;
BEGIN
 addcol('SHIPPING_SERVICE','VARCHAR2(100)');addcol('SHIPPING_SERVICE_NAME','NVARCHAR2(255)');addcol('SHIPPING_QUOTED_AT','TIMESTAMP');
 INSERT INTO SHOP_MIGRATION(VERSION) SELECT 'V009' FROM DUAL WHERE NOT EXISTS(SELECT 1 FROM SHOP_MIGRATION WHERE VERSION='V009');COMMIT;
END;
