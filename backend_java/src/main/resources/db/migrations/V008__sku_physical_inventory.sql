-- Run with application writers stopped. Every DDL checks existence; Oracle DDL may commit.
-- Snapshot tables are deliberately retained for reconciliation and rollback.
DECLARE
 n NUMBER;
 PROCEDURE addcol(t VARCHAR2,c VARCHAR2,d VARCHAR2) IS BEGIN
  SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME=t AND COLUMN_NAME=c;
  IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE '||t||' ADD ('||c||' '||d||')'; END IF;
 END;
 PROCEDURE snapshot(t VARCHAR2,b VARCHAR2) IS BEGIN
  SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME=b;
  IF n=0 THEN EXECUTE IMMEDIATE 'CREATE TABLE '||b||' AS SELECT * FROM '||t; END IF;
 END;
BEGIN
 snapshot('PRODUCT_DETAIL','V008_BACKUP_PD'); snapshot('BILL','V008_BACKUP_BILL');
 snapshot('BILL_DETAIL','V008_BACKUP_BD'); snapshot('INVENTORY_DOCUMENT','V008_BACKUP_DOC');
 snapshot('INVENTORY_DOCUMENT_LINE','V008_BACKUP_LINE'); snapshot('INVENTORY_HISTORY','V008_BACKUP_HISTORY');
 snapshot('PRODUCT','V008_BACKUP_PRODUCT');
 snapshot('ADMIN_AUDIT','V008_BACKUP_AUDIT');
 addcol('PRODUCT_DETAIL','PHYSICAL_QUANTITY','NUMBER(10) DEFAULT 0 NOT NULL');
 EXECUTE IMMEDIATE 'ALTER TABLE PRODUCT_DETAIL MODIFY PHYSICAL_QUANTITY DEFAULT 0';
 addcol('PRODUCT_DETAIL','RESERVED_QUANTITY','NUMBER(10) DEFAULT 0 NOT NULL');
 addcol('PRODUCT_DETAIL','AVERAGE_COST','NUMBER(24,8)');
 addcol('PRODUCT_DETAIL','KNOWN_VALUE','NUMBER(30,8) DEFAULT 0 NOT NULL');
 addcol('PRODUCT_DETAIL','UNKNOWN_QUANTITY','NUMBER(24,8) DEFAULT 0 NOT NULL');
 addcol('PRODUCT_DETAIL','COST_RECONCILED_AT','TIMESTAMP');
 addcol('PRODUCT_DETAIL','STOCK_VERSION','NUMBER DEFAULT 0 NOT NULL');
 addcol('BILL','DISPATCHED','NUMBER(1) DEFAULT 0 NOT NULL');
 addcol('BILL_DETAIL','COST_TOTAL','NUMBER(20,0)');
 addcol('INVENTORY_DOCUMENT','REVENUE_DELTA','NUMBER(20,2) DEFAULT 0 NOT NULL');
 addcol('INVENTORY_DOCUMENT_LINE','EXPECTED_RESERVED','NUMBER(10)');
 addcol('INVENTORY_DOCUMENT_LINE','EXPECTED_VERSION','NUMBER');
 addcol('INVENTORY_DOCUMENT_LINE','PHYSICAL_BEFORE','NUMBER(10)');
 addcol('INVENTORY_DOCUMENT_LINE','PHYSICAL_AFTER','NUMBER(10)');
 addcol('INVENTORY_DOCUMENT_LINE','RESERVED_BEFORE','NUMBER(10)');
 addcol('INVENTORY_DOCUMENT_LINE','RESERVED_AFTER','NUMBER(10)');
 addcol('INVENTORY_DOCUMENT_LINE','VALUE_BEFORE','NUMBER(30,8)');
 addcol('INVENTORY_DOCUMENT_LINE','VALUE_AFTER','NUMBER(30,8)');
 addcol('INVENTORY_DOCUMENT_LINE','COGS_VALUE','NUMBER(20,0)');
 addcol('INVENTORY_HISTORY','PHYSICAL_CHANGE','NUMBER(10)');
 addcol('INVENTORY_HISTORY','RESERVED_CHANGE','NUMBER(10)');
 addcol('INVENTORY_HISTORY','PHYSICAL_BEFORE','NUMBER(10)');
 addcol('INVENTORY_HISTORY','PHYSICAL_AFTER','NUMBER(10)');
 addcol('INVENTORY_HISTORY','RESERVED_BEFORE','NUMBER(10)');
 addcol('INVENTORY_HISTORY','RESERVED_AFTER','NUMBER(10)');
 addcol('INVENTORY_HISTORY','VALUE_BEFORE','NUMBER(30,8)');
 addcol('INVENTORY_HISTORY','VALUE_AFTER','NUMBER(30,8)');
 addcol('INVENTORY_HISTORY','HISTORY_SCOPE','VARCHAR2(20) DEFAULT ''AVAILABLE_LEGACY'' NOT NULL');
 addcol('ADMIN_AUDIT','BEFORE_DATA','CLOB');addcol('ADMIN_AUDIT','AFTER_DATA','CLOB');addcol('ADMIN_AUDIT','REASON','NVARCHAR2(500)');
 FOR c IN (SELECT CONSTRAINT_NAME FROM USER_CONSTRAINTS WHERE TABLE_NAME='INVENTORY_DOCUMENT' AND CONSTRAINT_TYPE='C') LOOP
  -- Only the DOC_TYPE check contains RECEIPT; do not remove status/not-null constraints.
  DECLARE text VARCHAR2(4000); BEGIN SELECT SEARCH_CONDITION_VC INTO text FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME=c.CONSTRAINT_NAME;
   IF text LIKE '%DOC_TYPE%' AND text LIKE '%RECEIPT%' THEN EXECUTE IMMEDIATE 'ALTER TABLE INVENTORY_DOCUMENT DROP CONSTRAINT '||c.CONSTRAINT_NAME; END IF;
  END;
 END LOOP;
 EXECUTE IMMEDIATE 'ALTER TABLE INVENTORY_DOCUMENT ADD CONSTRAINT CK_INV_DOC_TYPES_V8 CHECK(DOC_TYPE IN (''RECEIPT'',''ISSUE'',''COUNT'',''RETURN'',''REVERSAL'',''SALE'',''CANCEL'',''RESERVE'',''RELEASE'',''DISPATCH''))';
 SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME='CK_BILL_STATUS';
 IF n>0 THEN EXECUTE IMMEDIATE 'ALTER TABLE BILL DROP CONSTRAINT CK_BILL_STATUS'; END IF;
 SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME='CK_BILL_STATUS_V8';
 IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE BILL ADD CONSTRAINT CK_BILL_STATUS_V8 CHECK(STATUS IN (0,1,2,3,4,5,6))'; END IF;
 SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME='STOCK_COST_ADJUSTMENT';
 IF n=0 THEN EXECUTE IMMEDIATE 'CREATE TABLE STOCK_COST_ADJUSTMENT(ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,PRODUCT_DETAIL_ID NUMBER NOT NULL REFERENCES PRODUCT_DETAIL(ID),PHYSICAL_QUANTITY NUMBER NOT NULL,BEFORE_COST NUMBER(24,8),AFTER_COST NUMBER(24,8),BEFORE_KNOWN_VALUE NUMBER(30,8),AFTER_VALUE NUMBER(30,8),REASON NVARCHAR2(500) NOT NULL,EVIDENCE NVARCHAR2(500) NOT NULL,CREATED_BY NUMBER NOT NULL REFERENCES MANAGER(ID),CREATED_AT TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL)'; END IF;
 SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME='BILL_REFUND';
 IF n=0 THEN EXECUTE IMMEDIATE 'CREATE TABLE BILL_REFUND(ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,BILL_ID NUMBER NOT NULL REFERENCES BILL(ID),RETURN_DOCUMENT_ID NUMBER NOT NULL REFERENCES INVENTORY_DOCUMENT(ID),AMOUNT NUMBER(20,2) NOT NULL CHECK(AMOUNT>0),STATUS VARCHAR2(12) NOT NULL CHECK(STATUS IN (''PAID'',''PENDING'',''FAILED'')),REFERENCE_CODE VARCHAR2(150) NOT NULL UNIQUE,REASON NVARCHAR2(500) NOT NULL,CREATED_BY NUMBER NOT NULL REFERENCES MANAGER(ID),CREATED_AT TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,PAID_AT TIMESTAMP)'; END IF;
END;
/
DECLARE n NUMBER; reserved NUMBER; invalid NUMBER;
BEGIN
 SELECT COUNT(*) INTO n FROM SHOP_MIGRATION WHERE VERSION='V008'; IF n>0 THEN RETURN; END IF;
 SELECT COUNT(*) INTO invalid FROM PRODUCT_DETAIL WHERE QUANTITY<0;
 IF invalid>0 THEN RAISE_APPLICATION_ERROR(-20008,'Negative legacy available quantity; reconcile before migration'); END IF;
 UPDATE PRODUCT_DETAIL pd SET RESERVED_QUANTITY=(SELECT NVL(SUM(d.QUANTITY),0) FROM BILL_DETAIL d JOIN BILL b ON b.ID=d.BILL_ID WHERE d.PRODUCT_DETAIL_ID=pd.ID AND d.DELETE_FLAG=0 AND b.DELETE_FLAG=0 AND b.STOCK_RESERVED=1 AND b.STATUS IN (0,1));
 UPDATE PRODUCT_DETAIL SET PHYSICAL_QUANTITY=QUANTITY+RESERVED_QUANTITY,AVERAGE_COST=NULL,KNOWN_VALUE=0,UNKNOWN_QUANTITY=QUANTITY+RESERVED_QUANTITY;
 UPDATE BILL SET DISPATCHED=CASE WHEN STATUS IN (2,3,5) THEN 1 ELSE 0 END,STOCK_RESERVED=CASE WHEN STATUS IN (0,1) THEN STOCK_RESERVED ELSE 0 END;
 -- Shared product averages are evidence only. Old COGS cannot be certified as per-SKU costs.
 UPDATE BILL_DETAIL SET COST_UNIT=NULL;
 INSERT INTO SHOP_MIGRATION(VERSION) VALUES('V008'); COMMIT;
END;
