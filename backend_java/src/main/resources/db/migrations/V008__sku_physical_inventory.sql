 SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME='CK_PD_BALANCE_V8';
 IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE PRODUCT_DETAIL ADD CONSTRAINT CK_PD_BALANCE_V8 CHECK(PHYSICAL_QUANTITY>=0 AND RESERVED_QUANTITY>=0 AND RESERVED_QUANTITY<=PHYSICAL_QUANTITY AND QUANTITY=PHYSICAL_QUANTITY-RESERVED_QUANTITY AND KNOWN_VALUE>=0 AND UNKNOWN_QUANTITY>=0)'; END IF;
END;
