-- =====================================================================
-- 1. ROLES - Vai trò của người dùng (khách hàng)
-- =====================================================================
CREATE TABLE ROLES (
    ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ROLE_CODE    VARCHAR2(50)    NOT NULL,
    ROLE_NAME    NVARCHAR2(100)  NOT NULL,
    DESCRIPTION  NVARCHAR2(500),
    DELETE_FLAG  NUMBER(1)       DEFAULT 0 NOT NULL,
    CREATED_AT   TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT   TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_ROLES_CODE UNIQUE (ROLE_CODE),
    CONSTRAINT CK_ROLES_DEL  CHECK (DELETE_FLAG IN (0,1))
);

-- =====================================================================
-- 2. USERS - Tài khoản đăng nhập của khách hàng
-- =====================================================================
CREATE TABLE USERS (
    ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ROLE_ID        NUMBER          NOT NULL,
    USERNAME       VARCHAR2(100)   NOT NULL,
    EMAIL          VARCHAR2(255)   NOT NULL,
    PASSWORD_HASH  VARCHAR2(255)   NOT NULL,
    STATUS         NUMBER(1)       DEFAULT 1 NOT NULL,   -- 1: hoạt động, 0: bị khóa
    LAST_LOGIN_AT  TIMESTAMP,
    DELETE_FLAG    NUMBER(1)       DEFAULT 0 NOT NULL,
    CREATED_AT     TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT     TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_USERS_USERNAME UNIQUE (USERNAME),
    CONSTRAINT UQ_USERS_EMAIL    UNIQUE (EMAIL),
    CONSTRAINT FK_USERS_ROLE     FOREIGN KEY (ROLE_ID) REFERENCES ROLES(ID),
    CONSTRAINT CK_USERS_STATUS   CHECK (STATUS IN (0,1)),
    CONSTRAINT CK_USERS_DEL      CHECK (DELETE_FLAG IN (0,1))
);

-- =====================================================================
-- 3. CUSTOMER - Thông tin khách hàng (1-1 với USERS)
-- =====================================================================
CREATE TABLE CUSTOMER (
    ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID     NUMBER          NOT NULL,
    FULL_NAME   NVARCHAR2(150)  NOT NULL,
    PHONE       VARCHAR2(20),
    GENDER      NUMBER(1),                -- 0: Nữ, 1: Nam, 2: Khác
    BIRTH_DATE  DATE,
    AVATAR_URL  VARCHAR2(500),
    DELETE_FLAG NUMBER(1)       DEFAULT 0 NOT NULL,
    CREATED_AT  TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT  TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_CUSTOMER_USER   UNIQUE (USER_ID),
    CONSTRAINT FK_CUSTOMER_USER   FOREIGN KEY (USER_ID) REFERENCES USERS(ID),
    CONSTRAINT CK_CUSTOMER_GENDER CHECK (GENDER IN (0,1,2)),
    CONSTRAINT CK_CUSTOMER_DEL    CHECK (DELETE_FLAG IN (0,1))
);

-- =====================================================================
-- 4. ADDRESS - Địa chỉ giao hàng của khách hàng
-- =====================================================================
CREATE TABLE ADDRESS (
    ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUSTOMER_ID     NUMBER          NOT NULL,
    RECEIVER_NAME   NVARCHAR2(150)  NOT NULL,
    RECEIVER_PHONE  VARCHAR2(20)    NOT NULL,
    PROVINCE        NVARCHAR2(100)  NOT NULL,   -- Tỉnh/Thành phố
    WARD            NVARCHAR2(100)  NOT NULL,   -- Phường/Xã
    DETAIL_ADDRESS  NVARCHAR2(300)  NOT NULL,   -- Số nhà, tên đường
    IS_DEFAULT      NUMBER(1)       DEFAULT 0 NOT NULL,
    DELETE_FLAG     NUMBER(1)       DEFAULT 0 NOT NULL,
    CREATED_AT      TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_ADDRESS_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(ID),
    CONSTRAINT CK_ADDRESS_DEFAULT  CHECK (IS_DEFAULT IN (0,1)),
    CONSTRAINT CK_ADDRESS_DEL      CHECK (DELETE_FLAG IN (0,1))
);

-- =====================================================================
-- 5. MANAGER_ROLE - Vai trò của tài khoản quản lý (admin)
