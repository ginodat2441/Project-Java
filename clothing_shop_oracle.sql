-- =====================================================================
-- 14. BILL - Hóa đơn / đơn hàng
--     Lưu snapshot thông tin người nhận để địa chỉ đổi sau này
--     không làm sai lịch sử đơn hàng.
-- =====================================================================
CREATE TABLE BILL (
    ID                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BILL_CODE         VARCHAR2(50)    NOT NULL,
    CUSTOMER_ID       NUMBER          NOT NULL,
    ADDRESS_ID        NUMBER,
    RECEIVER_NAME     NVARCHAR2(150)  NOT NULL,
    RECEIVER_PHONE    VARCHAR2(20)    NOT NULL,
    SHIPPING_ADDRESS  NVARCHAR2(600)  NOT NULL,
    SUB_TOTAL         NUMBER(15,2)    DEFAULT 0 NOT NULL,
    SHIPPING_FEE      NUMBER(15,2)    DEFAULT 0 NOT NULL,
    DISCOUNT_AMOUNT   NUMBER(15,2)    DEFAULT 0 NOT NULL,
    TOTAL_AMOUNT      NUMBER(15,2)    DEFAULT 0 NOT NULL,
    PAYMENT_METHOD    VARCHAR2(20)    NOT NULL,             -- COD, BANK, MOMO, VNPAY
    PAYMENT_STATUS    NUMBER(1)       DEFAULT 0 NOT NULL,   -- 0: chưa thanh toán, 1: đã thanh toán, 2: hoàn tiền
    STATUS            NUMBER(2)       DEFAULT 0 NOT NULL,   -- 0: chờ xác nhận, 1: đã xác nhận, 2: đang giao, 3: hoàn thành, 4: đã hủy, 5: trả hàng
    NOTE              NVARCHAR2(500),
    HANDLED_BY        NUMBER,                               -- manager xử lý đơn
    DELETE_FLAG       NUMBER(1)       DEFAULT 0 NOT NULL,
    CREATED_AT        TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT        TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_BILL_CODE        UNIQUE (BILL_CODE),
    CONSTRAINT FK_BILL_CUSTOMER    FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(ID),
    CONSTRAINT FK_BILL_ADDRESS     FOREIGN KEY (ADDRESS_ID)  REFERENCES ADDRESS(ID),
    CONSTRAINT FK_BILL_MANAGER     FOREIGN KEY (HANDLED_BY)  REFERENCES MANAGER(ID),
    CONSTRAINT CK_BILL_PAY_METHOD  CHECK (PAYMENT_METHOD IN ('COD','BANK','MOMO','VNPAY')),
    CONSTRAINT CK_BILL_PAY_STATUS  CHECK (PAYMENT_STATUS IN (0,1,2)),
    CONSTRAINT CK_BILL_STATUS      CHECK (STATUS IN (0,1,2,3,4,5)),
    CONSTRAINT CK_BILL_AMOUNT      CHECK (SUB_TOTAL >= 0 AND SHIPPING_FEE >= 0
                                          AND DISCOUNT_AMOUNT >= 0 AND TOTAL_AMOUNT >= 0),
    CONSTRAINT CK_BILL_DEL         CHECK (DELETE_FLAG IN (0,1))
);

-- =====================================================================
-- 15. BILL_DETAIL - Chi tiết hóa đơn
-- =====================================================================
CREATE TABLE BILL_DETAIL (
    ID                 NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BILL_ID            NUMBER        NOT NULL,
    PRODUCT_DETAIL_ID  NUMBER        NOT NULL,
    QUANTITY           NUMBER(10)    NOT NULL,
    UNIT_PRICE         NUMBER(15,2)  NOT NULL,     -- giá tại thời điểm mua
    TOTAL_PRICE        NUMBER(15,2)  NOT NULL,     -- QUANTITY * UNIT_PRICE
    DELETE_FLAG        NUMBER(1)     DEFAULT 0 NOT NULL,
    CREATED_AT         TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT         TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_BD_BILL   FOREIGN KEY (BILL_ID)           REFERENCES BILL(ID),
    CONSTRAINT FK_BD_PD     FOREIGN KEY (PRODUCT_DETAIL_ID) REFERENCES PRODUCT_DETAIL(ID),
    CONSTRAINT CK_BD_QTY    CHECK (QUANTITY > 0),
    CONSTRAINT CK_BD_PRICE  CHECK (UNIT_PRICE >= 0 AND TOTAL_PRICE >= 0),
    CONSTRAINT CK_BD_DEL    CHECK (DELETE_FLAG IN (0,1))
