-- Additive migration: customer cancellation/return requests, no existing orders changed.
DECLARE n NUMBER;
BEGIN
 SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME='BILL_CUSTOMER_REQUEST';
 IF n=0 THEN
  EXECUTE IMMEDIATE 'CREATE TABLE BILL_CUSTOMER_REQUEST (
   ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   BILL_ID NUMBER NOT NULL REFERENCES BILL(ID),
   CUSTOMER_ID NUMBER NOT NULL REFERENCES CUSTOMER(ID),
   REQUEST_TYPE VARCHAR2(10) NOT NULL CHECK(REQUEST_TYPE IN (''CANCEL'',''RETURN'')),
   STATUS VARCHAR2(12) DEFAULT ''PENDING'' NOT NULL CHECK(STATUS IN (''PENDING'',''APPROVED'',''REJECTED'')),
   REASON NVARCHAR2(500) NOT NULL,
   RESPONSE_NOTE NVARCHAR2(500),
   CREATED_AT TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
   REVIEWED_AT TIMESTAMP,
   REVIEWED_BY NUMBER REFERENCES MANAGER(ID))';
  EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX UQ_BILL_REQ_PENDING ON BILL_CUSTOMER_REQUEST(CASE WHEN STATUS=''PENDING'' THEN BILL_ID END)';
  EXECUTE IMMEDIATE 'CREATE INDEX IX_BILL_REQ_CUSTOMER ON BILL_CUSTOMER_REQUEST(CUSTOMER_ID,BILL_ID,CREATED_AT)';
 END IF;
 INSERT INTO SHOP_MIGRATION(VERSION) SELECT 'V012' FROM DUAL
 WHERE NOT EXISTS(SELECT 1 FROM SHOP_MIGRATION WHERE VERSION='V012');
 COMMIT;
END;
/
