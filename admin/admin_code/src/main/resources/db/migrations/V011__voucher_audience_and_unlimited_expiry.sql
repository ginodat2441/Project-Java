WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
DECLARE
 n NUMBER;
 PROCEDURE addcol(c VARCHAR2,t VARCHAR2) IS BEGIN
  SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS
   WHERE TABLE_NAME='VOUCHER' AND COLUMN_NAME=c;
  IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE VOUCHER ADD ('||c||' '||t||')'; END IF;
 END;
 PROCEDURE addcheck(c VARCHAR2,e VARCHAR2) IS BEGIN
  SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS
   WHERE TABLE_NAME='VOUCHER' AND CONSTRAINT_NAME=c;
  IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE VOUCHER ADD CONSTRAINT '||c||' CHECK ('||e||')'; END IF;
 END;
BEGIN
 EXECUTE IMMEDIATE 'ALTER TABLE VOUCHER MODIFY (ENDS_AT NULL)';
 addcol('NEW_ACCOUNT_DAYS','NUMBER(5)');
 addcol('NO_PREVIOUS_ORDERS','NUMBER(1) DEFAULT 0 NOT NULL');
 addcol('MINIMUM_ORDERS','NUMBER(10)');
 addcheck('CK_VOUCHER_NO_PREVIOUS_ORDERS','NO_PREVIOUS_ORDERS IN (0,1)');
 addcheck('CK_VOUCHER_NEW_ACCOUNT_DAYS','NEW_ACCOUNT_DAYS IS NULL OR NEW_ACCOUNT_DAYS BETWEEN 1 AND 36500');
 addcheck('CK_VOUCHER_MINIMUM_ORDERS','MINIMUM_ORDERS IS NULL OR MINIMUM_ORDERS >= 1');
 INSERT INTO SHOP_MIGRATION(VERSION)
  SELECT 'V011' FROM DUAL
   WHERE NOT EXISTS(SELECT 1 FROM SHOP_MIGRATION WHERE VERSION='V011');
 COMMIT;
END;
/
