DECLARE
  PROCEDURE add_column(t VARCHAR2, c VARCHAR2, d VARCHAR2) IS n NUMBER;
  BEGIN
    SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME=t AND COLUMN_NAME=c;
    IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE ' || t || ' ADD (' || c || ' ' || d || ')'; END IF;
  END;
BEGIN
  add_column('INVENTORY_DOCUMENT','WAREHOUSE_NAME','VARCHAR2(150 CHAR)');
  add_column('BILL_VIETTEL_DISPATCH','DOCUMENT_ID','NUMBER REFERENCES INVENTORY_DOCUMENT(ID)');
  add_column('BILL_VIETTEL_DISPATCH','SEND_STATE','VARCHAR2(16) DEFAULT ''RETRY'' NOT NULL');
  add_column('BILL_VIETTEL_DISPATCH','ATTEMPTS','NUMBER DEFAULT 0 NOT NULL');
  add_column('BILL_VIETTEL_DISPATCH','SERVICE_CODE','VARCHAR2(20)');
  add_column('BILL_VIETTEL_DISPATCH','WEIGHT_GRAMS','NUMBER');
  add_column('BILL_VIETTEL_DISPATCH','LAST_ERROR','VARCHAR2(300 CHAR)');
END;
/
BEGIN
  EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX UQ_INV_ACTIVE_DISPATCH ON INVENTORY_DOCUMENT (CASE
    WHEN DOC_TYPE=''DISPATCH'' AND STATUS IN (''DRAFT'',''POSTED'') THEN BILL_ID END)';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/
BEGIN
  EXECUTE IMMEDIATE 'CREATE TABLE BILL_VIETTEL_EVENT (
    BILL_ID NUMBER NOT NULL REFERENCES BILL(ID),
    STATUS_CODE NUMBER NOT NULL,
    EVENT_AT TIMESTAMP NOT NULL,
    STATUS_NAME VARCHAR2(300 CHAR),
    CONSTRAINT PK_BILL_VIETTEL_EVENT PRIMARY KEY (BILL_ID,EVENT_AT,STATUS_CODE)
  )';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/
UPDATE BILL_VIETTEL_DISPATCH SET SEND_STATE='LINKED'
WHERE SEND_STATE='RETRY' AND EXISTS (SELECT 1 FROM BILL_VIETTEL_TRACKING t
  WHERE t.BILL_ID=BILL_VIETTEL_DISPATCH.BILL_ID)
/
MERGE INTO BILL_VIETTEL_DISPATCH x USING (
  SELECT d.BILL_ID,d.ID DOCUMENT_ID,CASE WHEN t.BILL_ID IS NULL THEN 'DRAFT' ELSE 'LINKED' END STATE
  FROM INVENTORY_DOCUMENT d LEFT JOIN BILL_VIETTEL_TRACKING t ON t.BILL_ID=d.BILL_ID
  WHERE d.BILL_ID IS NOT NULL AND d.DOC_TYPE='DISPATCH' AND d.STATUS IN ('DRAFT','POSTED')
) source ON (x.BILL_ID=source.BILL_ID)
WHEN MATCHED THEN UPDATE SET x.DOCUMENT_ID=source.DOCUMENT_ID WHERE x.DOCUMENT_ID IS NULL
WHEN NOT MATCHED THEN INSERT (BILL_ID,DOCUMENT_ID,SEND_STATE)
VALUES (source.BILL_ID,source.DOCUMENT_ID,source.STATE)
/
COMMIT
/
