CREATE TABLE VOUCHER_PRODUCT (
 VOUCHER_ID NUMBER NOT NULL REFERENCES VOUCHER(ID) ON DELETE CASCADE,
 PRODUCT_ID NUMBER NOT NULL REFERENCES PRODUCT(ID),
 CONSTRAINT PK_VOUCHER_PRODUCT PRIMARY KEY(VOUCHER_ID,PRODUCT_ID)
);
INSERT INTO VOUCHER_PRODUCT(VOUCHER_ID,PRODUCT_ID)
 SELECT v.ID,p.ID FROM VOUCHER v CROSS JOIN PRODUCT p WHERE p.DELETE_FLAG=0;
